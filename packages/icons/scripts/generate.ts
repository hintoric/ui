/**
 * svg/<slug>/{light,dark}.svg → src/generated/: one module per icon plus an
 * index. Runs before every build, test and typecheck; the output is not
 * committed, svg/ is.
 */
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { SLUG, componentName, toNestedSvg } from './svg.ts';

const pkg = join(import.meta.dirname, '..');
const svgRoot = join(pkg, 'svg');
const out = join(pkg, 'src', 'generated');
const CDN = 'https://cdn.hintoric.com';
const HEADER = '// Generated by scripts/generate.ts from svg/ — do not edit.\n';

const slugs = existsSync(svgRoot)
  ? (await readdir(svgRoot, { withFileTypes: true }))
      .filter((e) => e.isDirectory() && existsSync(join(svgRoot, e.name, 'light.svg')))
      .map((e) => e.name)
      .sort()
  : [];

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

const names: string[] = [];
for (const slug of slugs) {
  if (!SLUG.test(slug)) throw new Error(`svg/${slug}: folder name is not a kebab-case slug`);
  const name = componentName(slug);
  const variant = async (v: 'light' | 'dark') => {
    const file = join(svgRoot, slug, `${v}.svg`);
    if (!existsSync(file)) return null;
    try {
      return toNestedSvg(await readFile(file, 'utf8'), { idPrefix: `hi-${slug}-${v}-`, className: `hi-icon-${v}` });
    } catch (e) {
      throw new Error(`svg/${slug}/${v}.svg: ${(e as Error).message}`);
    }
  };
  const light = (await variant('light'))!;
  const dark = await variant('dark');
  const def = {
    slug,
    name,
    viewBox: light.viewBox,
    light: light.markup,
    dark: dark?.markup ?? null,
    cdn: {
      light: `${CDN}/assets/icons/${slug}/light.svg`,
      dark: dark ? `${CDN}/assets/icons/${slug}/dark.svg` : null,
    },
  };
  await writeFile(
    join(out, `${name}.ts`),
    `${HEADER}import { createIcon } from '../createIcon';\n\nexport const ${name} = /* @__PURE__ */ createIcon(${JSON.stringify(def, null, 2)});\n`,
  );
  names.push(name);
}

await writeFile(
  join(out, 'index.ts'),
  HEADER +
    "import type { HintoricIcon } from '../createIcon';\n" +
    names.map((n) => `import { ${n} } from './${n}';\n`).join('') +
    (names.length ? `\nexport { ${names.join(', ')} };\n` : '') +
    `\n/** Every icon, sorted by slug — for galleries and pickers. Importing it pulls in all of them. */\n` +
    `export const icons: readonly HintoricIcon[] = [${names.join(', ')}];\n`,
);
console.log(`generated ${names.length} icon(s)`);
